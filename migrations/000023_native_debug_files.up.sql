CREATE TABLE native_debug_file_blobs (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id         bigint NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    content_sha256     bytea NOT NULL,
    compressed_file    bytea NOT NULL,
    uncompressed_bytes bigint NOT NULL CHECK (uncompressed_bytes > 0 AND uncompressed_bytes <= 209715200),
    created_at         timestamptz NOT NULL DEFAULT now(),
    UNIQUE (project_id, content_sha256),
    UNIQUE (project_id, id)
);

CREATE TABLE native_debug_file_refs (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id   bigint NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    blob_id      bigint NOT NULL,
    debug_id     uuid NOT NULL,
    object_index integer NOT NULL CHECK (object_index >= 0),
    cpu_name     text NOT NULL,
    vmaddr       numeric(20,0) NOT NULL CHECK (vmaddr >= 0),
    uploaded_at  timestamptz NOT NULL DEFAULT now(),
    UNIQUE (project_id, debug_id),
    FOREIGN KEY (project_id, blob_id)
        REFERENCES native_debug_file_blobs(project_id, id) ON DELETE CASCADE
);

CREATE INDEX native_debug_file_refs_blob_idx ON native_debug_file_refs(blob_id);
