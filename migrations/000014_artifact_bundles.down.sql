-- Debug-id-addressed refs have no representation in source_maps and are lost
-- on the way down. Nothing else can be true: source_maps is keyed by
-- (release_id, generated_path), which a debug-id ref does not have.
CREATE TABLE source_maps (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    release_id bigint NOT NULL REFERENCES releases(id) ON DELETE CASCADE,
    generated_path text NOT NULL,
    content_sha256 bytea NOT NULL,
    compressed_map bytea NOT NULL,
    uncompressed_bytes bigint NOT NULL CHECK (uncompressed_bytes > 0 AND uncompressed_bytes <= 52428800),
    uploaded_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (release_id, generated_path)
);

INSERT INTO source_maps (release_id, generated_path, content_sha256, compressed_map, uncompressed_bytes, uploaded_at)
SELECT f.release_id, f.generated_path, b.content_sha256, b.compressed_map, b.uncompressed_bytes, f.uploaded_at
FROM source_map_refs AS f
JOIN source_map_blobs AS b ON b.id = f.blob_id
WHERE f.debug_id IS NULL;

ALTER TABLE releases DROP COLUMN released_at;
DROP TABLE upload_chunks;
DROP TABLE source_map_refs;
DROP TABLE source_map_blobs;
