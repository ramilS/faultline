CREATE TABLE artifact_tokens (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id bigint NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    name text NOT NULL CHECK (char_length(name) BETWEEN 1 AND 100),
    token_prefix text NOT NULL UNIQUE,
    token_hash bytea NOT NULL UNIQUE,
    created_at timestamptz NOT NULL DEFAULT now(),
    last_used_at timestamptz,
    revoked_at timestamptz
);

CREATE TABLE source_maps (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    release_id bigint NOT NULL REFERENCES releases(id) ON DELETE CASCADE,
    generated_path text NOT NULL,
    content_sha256 bytea NOT NULL,
    compressed_map bytea NOT NULL,
    uncompressed_bytes bigint NOT NULL CHECK (uncompressed_bytes > 0 AND uncompressed_bytes <= 52428800),
    uploaded_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (release_id, generated_path)
);
