CREATE TABLE source_map_blobs (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id         bigint NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    content_sha256     bytea  NOT NULL,
    compressed_map     bytea  NOT NULL,
    uncompressed_bytes bigint NOT NULL CHECK (uncompressed_bytes > 0
                                          AND uncompressed_bytes <= 52428800),
    created_at         timestamptz NOT NULL DEFAULT now(),
    UNIQUE (project_id, content_sha256)
);

CREATE TABLE source_map_refs (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    blob_id        bigint NOT NULL REFERENCES source_map_blobs(id) ON DELETE CASCADE,
    project_id     bigint NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    release_id     bigint REFERENCES releases(id) ON DELETE CASCADE,
    generated_path text,
    debug_id       uuid,
    uploaded_at    timestamptz NOT NULL DEFAULT now(),
    CHECK ((debug_id IS NOT NULL)
       <> (release_id IS NOT NULL AND generated_path IS NOT NULL))
);

CREATE UNIQUE INDEX source_map_refs_release_idx
    ON source_map_refs (release_id, generated_path) WHERE debug_id IS NULL;
CREATE UNIQUE INDEX source_map_refs_debug_idx
    ON source_map_refs (project_id, debug_id) WHERE debug_id IS NOT NULL;

-- Postgres does not index a foreign key column for you, and the two unique
-- indexes above lead with release_id and project_id respectively, so neither
-- serves a lookup by blob_id. Without these, every ON DELETE CASCADE from
-- source_map_blobs and from projects sequentially scans source_map_refs.
CREATE INDEX source_map_refs_blob_idx ON source_map_refs (blob_id);
CREATE INDEX source_map_refs_project_idx ON source_map_refs (project_id);

CREATE TABLE upload_chunks (
    project_id bigint NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    checksum   bytea  NOT NULL,
    body       bytea  NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (project_id, checksum)
);
CREATE INDEX upload_chunks_gc_idx ON upload_chunks (created_at);

ALTER TABLE releases ADD COLUMN released_at timestamptz;

INSERT INTO source_map_blobs (project_id, content_sha256, compressed_map, uncompressed_bytes, created_at)
SELECT DISTINCT ON (r.project_id, m.content_sha256)
       r.project_id, m.content_sha256, m.compressed_map, m.uncompressed_bytes, m.uploaded_at
FROM source_maps AS m
JOIN releases AS r ON r.id = m.release_id
ORDER BY r.project_id, m.content_sha256, m.uploaded_at;

INSERT INTO source_map_refs (blob_id, project_id, release_id, generated_path, uploaded_at)
SELECT b.id, r.project_id, m.release_id, m.generated_path, m.uploaded_at
FROM source_maps AS m
JOIN releases AS r ON r.id = m.release_id
JOIN source_map_blobs AS b
  ON b.project_id = r.project_id AND b.content_sha256 = m.content_sha256;

DROP TABLE source_maps;
