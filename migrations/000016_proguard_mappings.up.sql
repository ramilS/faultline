CREATE TABLE proguard_mappings (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id         bigint NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    mapping_uuid       uuid   NOT NULL,
    content_sha256     bytea  NOT NULL,
    compressed_mapping bytea  NOT NULL,
    uncompressed_bytes bigint NOT NULL CHECK (uncompressed_bytes > 0
                                          AND uncompressed_bytes <= 104857600),
    uploaded_at        timestamptz NOT NULL DEFAULT now(),
    UNIQUE (project_id, mapping_uuid)
);
